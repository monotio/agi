import type { Speedrun } from "./runner.ts";

/** Player inputs for the opening Daventry circuit; no game-state writes. */
export function firstHalf(run: Speedrun): void {
  run.checkpoint("Daventry", { room: 1, score: 0 });
  run.walkTo(110, 135);
  run.walkTo(100, 150);
  run.exit("W", 2);
  run.walkTo(110, 150);
  run.walkTo(110, 124);
  run.command("open door");
  run.wait(() => run.state().room === 55, "Castle door opens", 1200);
  run.checkpoint("Castle door", { room: 55, score: 1 });
  run.exit("N", 54);
  run.walkTo(run.state().x, 120);
  run.exit("W", 53);
  run.walkTo(75, 110);
  run.command("bow");
  run.advance(120);
  run.dismiss();
  run.checkpoint("Audience", { room: 53, score: 4 });
  run.command("talk to king");
  run.key(13);
  run.advance(12);
  run.walkTo(145, 120);
  run.exit("E", 54);
  run.walkTo(79, 130);
  run.exit("S", 55);
  run.exit("S", 2);
  run.walkTo(110, 150);
  run.walkTo(58, 150);
  run.walkTo(45, 137);
  run.walkTo(20, 137);
  run.exit("W", 3);
  run.walkTo(123, 120);
  run.command("push rock");
  run.advance(120);
  run.command("get dagger");
  run.checkpoint("Dagger", { room: 3, score: 11 });
  run.walkTo(115, 115);
  run.exit("N", 14);
  run.command("climb tree");
  run.checkpoint("Tree", { room: 63, score: 13 });
  run.walkTo(50, 145);
  run.walkTo(60, 120);
  run.walkTo(60, 105);
  run.walkTo(68, 97);
  run.command("get egg");
  run.checkpoint("Golden egg", { room: 63, score: 19 });
  run.walkTo(60, 105);
  run.walkTo(60, 120);
  run.walkTo(50, 145);
  run.walkTo(35, 164);
  run.exit("S", 14);
  run.walkTo(84, 130);
  run.walkTo(140, 130);
  run.exit("E", 15);
  run.walkTo(15, 140);
  run.walkTo(50, 140);
  run.command("get carrot");
  run.checkpoint("Carrot", { room: 15, score: 21 });
  run.exit("E", 16);
  run.exit("E", 9);
  run.exit("N", 24);
  run.walkTo(53, 140);
  run.command("get clover");
  run.checkpoint("Clover", { room: 24, score: 23 });
}

/** Lead the goat to the troll and solve the gnome's name through player input. */
export function beans(run: Speedrun): void {
  run.checkpoint("Stump departure", { room: 6, score: 67 });
  run.walkTo(50, 130);
  run.exit("N", 11);
  run.walkTo(30, 160);
  run.command("open gate");
  run.wait(() => run.engine.flags[78] !== 0, "goat gate opens");
  run.walkTo(30, 140);
  run.walkTo(40, 120);
  run.command("show carrot");
  run.checkpoint("Goat", { room: 11, score: 72 });
  run.walkTo(20, 140);
  run.walkTo(20, 162);
  run.exit("W", 10);
  run.walkTo(70, 162);
  run.exit("S", 7);
  run.walkTo(135, 50);
  run.walkTo(135, 90);
  run.walkTo(110, 110);
  run.exit("S", 42);
  run.walkTo(99, 90);
  run.walkTo(115, 95);
  run.exit("S", 39);
  run.walkTo(135, 45);
  run.walkTo(145, 65);
  run.walkTo(145, 80);
  run.walkTo(85, 75);
  run.walkTo(60, 70);
  run.wait(() => run.engine.flags[150] !== 0, "goat removes troll");
  run.checkpoint("Troll", { room: 39, score: 76 });
  run.exit("W", 40);
  run.walkTo(45, 110);
  run.walkTo(40, 130);
  run.command("talk to gnome");
  run.command("ifnkovhgroghprm");
  run.walkTo(40, 120);
  run.command("get beans");
  run.checkpoint("Beans", { room: 40, score: 85 });
  run.walkTo(110, 120);
  run.walkTo(145, 100);
  run.walkTo(145, 70);
  run.exit("E", 39);
  run.exit("E", 38);
  run.command("plant beans");
  run.checkpoint("Beanstalk", { room: 38, score: 87 });
}
